import fs from 'node:fs';
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';

// Exercise the actual activity with all saves intercepted in memory.
let record=JSON.parse(fs.readFileSync('tests/fixtures/booklets/linear-legacy-layout.json','utf8'));
const section=record.sections.find(s=>s.blocks.some(b=>b.id==='page-4-q1'));
record.sections=[{...section,blocks:[section.blocks.find(b=>b.id==='page-4-q1')]}];
record.studio={};
record.settings.preserveSourcePages=false;
record.sections[0].blocks[0].content.prompt='Interpret Coordinates';
delete record.settings.layoutOverrides.blockLayouts['page-4-q1'];
const children=JSON.stringify(record.sections[0].blocks[0].content.children);
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/__booklet/**',r=>r.request().method()==='GET'?r.continue():r.abort());
await page.route('**/__booklet/bank/manifest',r=>r.fulfill({json:{format:'mathsmap-practice-bank-v3',version:3,questions:[]}}));
await page.route('**/__booklet/projects',r=>r.fulfill({json:[record]}));
await page.route('**/__booklet/projects/'+record.id,async r=>{
 if(r.request().method()==='PUT')record={...r.request().postDataJSON().project,revision:record.revision+1};
 await r.fulfill({json:record});
});
const dialog=page.locator('.focused-editor');
const prompt='.paper-scroll [data-arrangement-id="layout:page-4-q1-root/prompt"]';
const parts='.paper-scroll [data-arrangement-id="page-4-q1-root:parts"]';
const save=async()=>{await dialog.locator(':scope > header').getByRole('button',{name:'Save',exact:true}).click();await page.waitForFunction(()=>document.querySelector('.save-state')?.textContent==='Saved');};
try{
 await page.goto((process.argv[2]??'http://127.0.0.1:5173')+'/#/booklet?stage=projects&project='+record.id);
 await page.locator(prompt).waitFor();
 const topBefore=(await page.locator(parts).boundingBox()).y;
 await page.locator(prompt).click();
 await dialog.getByRole('button',{name:'Edit selected content',exact:true}).click();
 await dialog.locator('.me-content p').first().click();
 await page.keyboard.press('ControlOrMeta+A');await page.keyboard.press('Backspace');
 await dialog.getByRole('button',{name:'Apply to question',exact:true}).click();
 assert.equal(await dialog.locator('.arr-canvas [data-arrangement-id*="root/prompt"]').count(),0);
 await save();
 assert.equal(await page.locator(prompt).count(),0);
 assert.ok((await page.locator(parts).boundingBox()).y<topBefore-10,'clearing text collapses its gap');
 await page.reload();await page.locator(parts).waitFor();
 assert.equal(await page.locator('.paper-scroll [data-arrangement-id*="root/prompt"]').count(),0);
 await page.locator('.block-list summary').first().click();
 await page.getByRole('button',{name:'Block properties',exact:true}).click();
 await page.getByRole('button',{name:'Edit question content',exact:true}).click();
 await dialog.getByRole('button',{name:'Add text',exact:true}).click();
 await dialog.locator('.me-content p').first().click();
 await page.keyboard.press('ControlOrMeta+A');await page.keyboard.type('Read each coordinate.');
 await dialog.getByRole('button',{name:'Apply to question',exact:true}).click();
 assert.match(await dialog.locator('.arr-canvas').innerText(),/Read each coordinate/);
 await dialog.getByRole('button',{name:'Remove text',exact:true}).click();
 assert.doesNotMatch(await dialog.locator('.arr-canvas').innerText(),/Read each coordinate/);
 await dialog.getByRole('button',{name:'Undo edit',exact:true}).click();
 assert.match(await dialog.locator('.arr-canvas').innerText(),/Read each coordinate/);
 await dialog.getByRole('button',{name:'Redo edit',exact:true}).click();
 assert.doesNotMatch(await dialog.locator('.arr-canvas').innerText(),/Read each coordinate/);
 await dialog.getByRole('button',{name:'Undo edit',exact:true}).click();
 await save();
 await page.reload();await page.locator(parts).waitFor();
 assert.match(await page.locator('.paper-scroll').innerText(),/Read each coordinate/);
 assert.equal(JSON.stringify(record.sections[0].blocks[0].content.children),children);
 assert.equal(await page.locator('.paper-scroll [role="alert"]').count(),0);
 await page.getByRole('button',{name:'Close panel',exact:true}).click();
 await page.getByLabel('Booklet zoom',{exact:true}).selectOption('page');
 fs.mkdirSync('output/text-controls',{recursive:true});
 await page.locator('.paper-scroll .preview-page').screenshot({path:'output/text-controls/restored-prompt.png'});
 assert.deepEqual(errors,[]);
 console.log('Text controls passed: clear/collapse, save/reload, restore, remove, undo/redo, unchanged parts and answers.');
}catch(error){console.error(errors,await page.locator('body').innerText());throw error;}finally{await browser.close();}
