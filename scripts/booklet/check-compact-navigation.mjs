import fs from 'node:fs';
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {exerciseNumbers,isPractice} from '../../src/lib/booklet-flow.js';
const arg=(name,fallback)=>{const i=process.argv.indexOf(name);return i<0?fallback:process.argv[i+1];};
const id=arg('--project','linear-relationships-v1'),out=arg('--out','.booklet-work/compact-exercises'),base=arg('--base','http://127.0.0.1:5173');
if(!/^[a-zA-Z0-9._-]+$/.test(id))throw Error('Invalid project ID');
fs.mkdirSync(out,{recursive:true});
const record=JSON.parse(fs.readFileSync(`booklets/projects/${id}.json`));record.settings.flowEdition='with-short';
const browser=await chromium.launch({headless:true,channel:'chrome'}),context=await browser.newContext({viewport:{width:1600,height:1100},...(fs.existsSync(out+'/cache.json')?{storageState:out+'/cache.json'}:{})}),page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.route('**/__booklet/**',r=>r.request().method()==='GET'?r.fallback():r.abort());
await page.route('**/__booklet/projects/'+id,r=>r.fulfill({json:record}));
const ready=async()=>{await page.waitForFunction(()=>{const el=document.querySelector('.flow-document');return el?.dataset.paginationState==='ready'&&el.dataset.paginatedEdition==='with-short';},null,{timeout:600000});};
try{
 await page.goto(base+'/#/booklet?stage=projects&project='+id,{waitUntil:'domcontentloaded'});await ready();
 const url=page.url(),count=await page.locator('.page-marker').count();
 const firstPractice=record.sections.find(s=>s.blocks.some(isPractice)),exercise=exerciseNumbers(record)[firstPractice?.topicId];
 if(!exercise)throw Error('Navigation check requires a numbered exercise');
 await page.locator(`.flow-document a[href="#screen-exercise-topic-${exercise}"]`).click();
 await page.locator(`.flow-document #screen-exercise-topic-${exercise}`).waitFor({state:'visible'});
 const questionId=firstPractice.blocks.find(isPractice)?.id;
 if(!questionId)throw Error('Navigation check requires a practice question');
 await page.evaluate(()=>window.dispatchEvent(new Event('booklet-prepare-print')));
 await page.locator('.project-print .print-page').first().waitFor({state:'attached'});
 const number=await page.locator('.project-print .print-page').evaluateAll((pages,id)=>Number(pages.find(p=>p.dataset.flowBlocks?.split(',').includes(id))?.dataset.flowPage),questionId);
 assert.ok(Number.isInteger(number),'Selected question has a calculated page');
 await page.getByLabel('Jump to page',{exact:true}).fill(String(number));await page.getByLabel('Jump to page',{exact:true}).press('Tab');
 const question=page.locator('.flow-document [id="screen-question-'+questionId+'"]');await question.waitFor({state:'visible'});
 assert.ok(await question.locator('[data-editor-difficulty]').count());
 await question.locator('.answer-jump').click();
 const answer=page.locator('.flow-document [id="screen-answer-short-'+questionId+'"]');await answer.waitFor({state:'visible'});
 await answer.locator('.answer-label a').first().click();await question.waitFor({state:'visible'});assert.equal(page.url(),url);
 await page.getByLabel('Booklet zoom',{exact:true}).selectOption('0.75');assert.equal(await page.locator('.page-marker').count(),count);
 await page.setViewportSize({width:390,height:844});await page.getByLabel('Booklet zoom',{exact:true}).selectOption('width');assert.equal(await page.locator('.page-marker').count(),count);
 await page.screenshot({path:out+'/navigation-mobile.png'});
 await page.setViewportSize({width:1600,height:1100});await page.reload({waitUntil:'domcontentloaded'});await ready();assert.equal(await page.locator('.page-marker').count(),count);
 assert.deepEqual(errors,[]);fs.writeFileSync(out+'/navigation.json',JSON.stringify({pages:count,contents:true,questionToAnswer:true,answerToQuestion:true,editorDifficulty:true,zoom:true,mobile:true,reload:true,errors},null,2));
 console.log('Editor navigation, difficulty badges, zoom, mobile and reload passed.');
}finally{await browser.close();}
